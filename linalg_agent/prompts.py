def render_solve_user(problem: str, method: Method | None) -> str:
    if method is None:
        constraint = (
            "未指定写法。请只自选矩阵解法或线性空间解法中的一种，"
            "在解法开头声明，不要两种都写。"
        )
    else:
        constraint = (
            f"必须使用{method.label}，不要改用{method.other.label}。"
            "题目原文若要求另一种，仍以这里的指定为准。"
        )
    return f"【题目】\n{problem}\n\n【写法】\n{constraint}\n"


def render_translate_user(problem: str, given_solution: str, given_method: Method) -> str:
    target = given_method.other
    return (
        f"【题目】\n{problem}\n\n"
        f"【已有解法类型】\n{given_method.label}\n\n"
        f"【必须给出】\n{target.label}\n\n"
        "【翻译规则】\n"
        "这是翻译，不是重新选题。沿用已有解法里合法的不唯一选择，"
        "不要改成你自己更习惯的取法。\n"
        "若其中有计算错误，可核对结论写改正后的结果；"
        "约定仍沿用说得通的原取法，并在检验中指出错误。\n\n"
        f"【已有解法】\n{given_solution}\n"
    )
